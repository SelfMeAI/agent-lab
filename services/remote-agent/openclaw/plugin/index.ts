const tasks = "/home/node/.openclaw/workspace/selfme";
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const maxUpload = 20 * 1024 * 1024;

export function taskId(value: unknown): string {
  if (typeof value !== "string" || !uuid.test(value)) throw new Error("任务标识无效"); return value;
}
export function relativeFile(value: unknown): string {
  if (typeof value !== "string" || value.includes("\0") || value.includes("\\") || value.startsWith("/") || value.split("/").some(part => part === ".." || part.startsWith(".selfme-"))) throw new Error("文件路径无效");
  return value;
}
async function root(id: string): Promise<string> {
  const path = join(tasks, taskId(id));
  if ((await readFile(join(path, ".selfme-workspace"), "utf8")) !== id) throw new Error("任务工作区未准备好");
  const actual = await realpath(path);
  if (actual !== path) throw new Error("任务工作区不能是符号链接"); return actual;
}
async function target(id: string, file: string, write = false): Promise<string> {
  const base = await root(id); const path = resolve(base, relativeFile(file));
  const parent = write ? await realpath(dirname(path)) : await realpath(path);
  if (parent !== base && !parent.startsWith(base + sep)) throw new Error("文件超出任务工作区"); return path;
}
function reply(res: ServerResponse, code: number, value: unknown): void {
  res.writeHead(code, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" }); res.end(JSON.stringify(value));
}
async function http(req: IncomingMessage, res: ServerResponse): Promise<boolean> {
  try {
    const url = new URL(req.url ?? "/", "http://localhost"); const id = taskId(url.searchParams.get("task")); const path = relativeFile(url.searchParams.get("path") ?? "");
    if (req.method === "GET" && url.searchParams.get("op") === "list") {
      const directory = await target(id, path); const entries = await readdir(directory, { withFileTypes: true });
      const files = [];
      for (const entry of entries.slice(0, 500)) {
        if (entry.isSymbolicLink() || entry.name.startsWith(".selfme-")) continue;
        const info = await stat(join(directory, entry.name));
        files.push({ path: path ? path + "/" + entry.name : entry.name, name: entry.name, directory: info.isDirectory(), size: info.size, modifiedAt: info.mtime.toISOString() });
      }
      reply(res, 200, { path, files, truncated: entries.length > 500 }); return true;
    }
    if (req.method === "PUT") {
      if (!path.startsWith("uploads/") || path.split("/").length !== 2) throw new Error("上传仅限任务 uploads 目录");
      const base = await root(id); await mkdir(join(base, "uploads"), { recursive: true });
      const destination = await target(id, path, true); const temporary = join(base, "uploads", ".selfme-upload-" + randomUUID());
      const handle = await open(temporary, "wx", 0o600); let size = 0; let reserved = false;
      try {
        // Reject an overwrite, including dangling symlinks. Names are generated by the client.
        try { const existing = await open(destination, "wx"); await existing.close(); reserved = true; } catch { throw new Error("同名文件已存在，未覆盖"); }
        for await (const chunk of req) { size += chunk.length; if (size > maxUpload) throw new Error("单个文件最多 20 MB"); await handle.write(chunk); }
        await handle.close(); await rename(temporary, destination);
      } catch (error) { await handle.close().catch(() => {}); await unlink(temporary).catch(() => {}); if (reserved) await unlink(destination).catch(() => {}); throw error; }
      reply(res, 200, { path, name: basename(path), size, directory: false, absolutePath: destination }); return true;
    }
    if (req.method !== "GET") { reply(res, 405, { error: "不支持此操作" }); return true; }
    const file = await target(id, path); const info = await stat(file);
    if (!info.isFile() || info.size > 64 * 1024 * 1024) throw new Error("文件不存在，或超过 64 MB 下载上限");
    res.writeHead(200, { "Content-Type": "application/octet-stream", "Content-Length": info.size, "Cache-Control": "no-store" });
    const stream = createReadStream(file); stream.on("error", () => res.destroy()); res.on("close", () => stream.destroy()); stream.pipe(res); return true;
  } catch (error) { if (!res.headersSent) reply(res, 400, { error: error instanceof Error ? error.message : "文件操作失败" }); else res.destroy(); return true; }
}

type DesktopLease = { env: NodeJS.ProcessEnv; isCurrent(): boolean; release(): void };
type HostDesktopService = { acquireComputer(options: { onStop(): Promise<void> }): Promise<DesktopLease> };
type PluginApi = {
  agent: { events: { registerAgentEventSubscription(subscription: { id: string; streams: string[]; handle(event: NativeExecutionEvent): void }): void } };
  lifecycle: { registerRuntimeLifecycle(registration: { id: string; dispose(): Promise<void> }): void };
  registerSessionCatalog(provider: { id: string; label: string; audience: "gateway-operators"; supportsProcessHomeIsolation: true; list(): Promise<[]>; read(): Promise<never>; openTerminal(request: { hostId: string; threadId: string }): Promise<{ kind: "local"; argv: string[]; cwd: string; title: string }> }): void;
  registerGatewayMethod(name: string, handler: (request: { params: Record<string, unknown>; context: { hostDesktopService?: HostDesktopService; chatAbortControllers: Map<string, unknown>; isTerminalEnabled(): boolean; terminalSessions?: { list(): { sessionId: string; cwd: string }[]; write(owner: string, id: string, data: string): boolean }; getRuntimeConfig(): { models?: { providers?: Record<string, { baseUrl?: string; api?: string; apiKey?: unknown }> } } }; client?: { connId?: string; connectionSignal?: AbortSignal }; respond(ok: boolean, value?: unknown, error?: { code: string; message: string }): void }) => Promise<void>, options: { scope: string }): void;
  registerHttpRoute(route: { path: string; auth: "gateway"; match: "exact"; handler: typeof http }): void;
  on(name: "before_tool_call", handler: () => { block: true; blockReason: string } | undefined, options?: { priority: number }): void;
};
let controlLease: { id: string; owner: string; task: string; ready: boolean } | undefined;
const browserChannels = new Map<string, BrowserInputChannel>();
function closeBrowserInput(): void { for (const channel of browserChannels.values()) channel.close(); browserChannels.clear(); }
let desktopLease: DesktopLease | undefined;
let preparingDesktop: Promise<void> | undefined;
// The container has one native managed desktop. Its allocated display and
// private D-Bus address must also reach native browser/exec/PTY children. Never
// guess :99 or start a second X server outside the native lifecycle.
async function prepareDesktop(service: HostDesktopService): Promise<void> {
  if (desktopLease?.isCurrent()) return;
  if (preparingDesktop) return preparingDesktop;
  const pending = (async () => {
    const previous = new Map<string, string | undefined>();
    let lease: DesktopLease;
    const restore = () => {
      for (const [name, value] of previous) if (process.env[name] === lease?.env[name]) {
        if (value === undefined) delete process.env[name]; else process.env[name] = value;
      }
      if (desktopLease === lease) desktopLease = undefined;
    };
    lease = await service.acquireComputer({ onStop: async () => { restore(); lease?.release(); } });
    if (!lease.isCurrent() || !/^:\d+$/.test(lease.env.DISPLAY ?? "")) { lease.release(); throw new Error("远端桌面显示服务未就绪"); }
    for (const name of ["DISPLAY", "DBUS_SESSION_BUS_ADDRESS", "XDG_SESSION_TYPE", "PULSE_SERVER", "PULSE_COOKIE"] as const) {
      if (lease.env[name] !== undefined) { previous.set(name, process.env[name]); process.env[name] = lease.env[name]; }
    }
    desktopLease = lease;
  })().finally(() => { if (preparingDesktop === pending) preparingDesktop = undefined; });
  preparingDesktop = pending; return pending;
}
export default {
  id: "selfme-lab", name: "SelfMe Lab Remote Files",
  register(api: PluginApi): void {
    const observer = new ExecutionObserver({ onRound: async task => { if (desktopLease?.isCurrent()) await showTerminal(task, true); }, onError: error => console.error("[selfme] Terminal observer:", error instanceof Error ? error.message : "unavailable") });
    api.agent.events.registerAgentEventSubscription({ id: "terminal-observer", streams: ["lifecycle", "tool", "command_output", "approval"], handle: event => observer.observe(event) });
    api.lifecycle.registerRuntimeLifecycle({ id: "terminal-observer", dispose: async () => { controlLease = undefined; closeBrowserInput(); await setTerminalControl(); await observer.dispose(); } });
    // Let the native PTY manager retain admission, custody and flow control.
    // Its catalog launch extension attaches the same tmux shell as the desktop.
    api.registerSessionCatalog({
      id: "selfme-lab-terminal", label: "SelfMe task terminals", audience: "gateway-operators", supportsProcessHomeIsolation: true,
      list: async () => [], read: async () => { throw new Error("此目录仅用于连接任务终端"); },
      openTerminal: async ({ hostId, threadId }) => {
        if (hostId !== "gateway") throw new Error("终端主机无效");
        const identity = await prepareTerminal(taskId(threadId));
        return { kind: "local", argv: terminalArgv(identity.task), cwd: identity.cwd, title: "Terminal · " + identity.task.slice(0, 8) };
      },
    });
    for (const operation of ["prepare", "dispose"] as const) api.registerGatewayMethod(`selfme.terminal.${operation}`, async ({ params, respond }) => {
      try {
        const id = taskId(params.task); await root(id);
        if (operation === "prepare") {
          if (!desktopLease?.isCurrent()) throw new Error("请先连接远端桌面");
          await showTerminal(id);
        } else { await observer.forget(id); await disposeTerminal(id); }
        respond(true, { ok: true });
      } catch (error) { respond(false, undefined, { code: "UNAVAILABLE", message: error instanceof Error ? error.message : "任务终端连接失败" }); }
    }, { scope: "operator.admin" });
    api.registerGatewayMethod("selfme.models.list", async ({ params, context, respond }) => {
      try {
        const provider = context.getRuntimeConfig().models?.providers?.selfme;
        const saved: ProviderModelsInput = { protocol: provider?.api === "anthropic-messages" ? "anthropic" : "openai", baseUrl: provider?.baseUrl ?? "", apiKey: typeof provider?.apiKey === "string" ? provider.apiKey : undefined };
        const models = await discoverConnectedModels(params as unknown as ProviderModelsInput, saved);
        respond(true, { models });
      } catch (error) { respond(false, undefined, { code: "INVALID_REQUEST", message: error instanceof Error ? error.message : "获取模型列表失败" }); }
    }, { scope: "operator.admin" });
    api.registerGatewayMethod("selfme.scene.prepare", async ({ params, context, respond }) => {
      try {
        const workspace = await root(taskId(params.task));
        if (!context.hostDesktopService) throw new Error("原生桌面服务不可用");
        await prepareDesktop(context.hostDesktopService);
        await setDesktopTask(taskId(params.task));
        respond(true, { root: workspace, display: desktopLease?.env.DISPLAY });
      } catch (error) { respond(false, undefined, { code: "UNAVAILABLE", message: error instanceof Error ? error.message : "现场准备失败" }); }
    }, { scope: "operator.write" });
    // The hold lives on the authenticated Gateway, not in a renderer flag.
    // RFB grants and this lease are both revoked when their owner disconnects.
    api.on("before_tool_call", () => controlLease ? { block: true, blockReason: "远端桌面正在由用户接管。停止操作，等待用户交还控制后再继续。" } : undefined, { priority: 10000 });
    for (const operation of ["acquire", "ready", "renew", "release"] as const) api.registerGatewayMethod(`selfme.control.${operation}`, async ({ params, context, client, respond }) => {
      try {
        const owner = client?.connId;
        if (!owner || !client?.connectionSignal || client.connectionSignal.aborted) throw new Error("接管需要持续的已认证连接");
        if (operation === "acquire") {
          if (controlLease) throw new Error("桌面已有接管者，请先交还控制");
          const lease = { id: randomUUID(), owner, task: taskId(params.task), ready: false }; await root(lease.task);
          if (controlLease) throw new Error("桌面已有接管者，请先交还控制");
          if (client.connectionSignal.aborted) throw new Error("接管连接已断开"); controlLease = lease;
          await setTerminalControl();
          client.connectionSignal.addEventListener("abort", () => { if (controlLease === lease) { controlLease = undefined; closeBrowserInput(); void setTerminalControl().catch(() => {}); } }, { once: true });
          respond(true, { id: lease.id }); return;
        }
        if (!controlLease || controlLease.owner !== owner || controlLease.id !== params.id) throw new Error("接管已结束或不属于此连接");
        if (operation === "ready") {
          if (context.chatAbortControllers.size) throw new Error("智能体仍有操作未停止，终端保持只读");
          controlLease.ready = true;
        }
        if (operation === "release") { controlLease = undefined; closeBrowserInput(); await setTerminalControl(); }
        else await setTerminalControl({ task: controlLease.task, ready: controlLease.ready, expiresAt: Date.now() + 45_000 });
        respond(true, { ok: true });
      } catch (error) { respond(false, undefined, { code: "INVALID_REQUEST", message: error instanceof Error ? error.message : "接管失败" }); }
    }, { scope: "operator.admin" });
    const browserQueues = new Map<string, Promise<void>>();
    for (const operation of ["input", "open"] as const) api.registerGatewayMethod(`selfme.browser.${operation}`, async ({ params, client, respond }) => {
      try {
        const task = taskId(params.task), lease = controlLease;
        const authorize = () => { if (client?.connectionSignal?.aborted || !client?.connId || !lease?.ready || controlLease !== lease || lease.owner !== client.connId || lease.task !== task) throw new Error("请先手动接管，再操作浏览器"); };
        authorize();
        const scope = params.tabScope as { sessionKey?: string } | undefined;
        if (scope?.sessionKey !== `agent:main:selfme:${task}`) throw new Error("浏览器页面不属于当前任务");
        // Public SDK dispatch keeps native authentication, target ownership and
        // navigation policy. No direct import or fork of harness internals.
        const { dispatchGatewayMethod } = await import("openclaw/plugin-sdk/gateway-method-runtime");
        const request = async (args: Record<string, unknown>) => {
          authorize(); const result = await dispatchGatewayMethod("browser.request", { ...args, tabScope: scope }); authorize();
          if (!result.ok) throw new Error(result.error?.message || "远端浏览器请求失败");
          return result.payload as Record<string, unknown>;
        };
        if (operation === "open") {
          if (typeof params.url !== "string" || params.url.length > 8192) throw new Error("浏览器地址无效");
          const url = new URL(params.url);
          if ((!['http:', 'https:'].includes(url.protocol) && url.href !== 'about:blank') || url.username || url.password) throw new Error("页面地址需要 HTTP(S)，不能包含登录凭据");
          const opened = await request({ method: "POST", path: "/tabs/open", body: { url: url.href } });
          await request({ method: "POST", path: "/tabs/focus", body: { targetId: opened.targetId } });
          respond(true, opened); return;
        }
        const targetId = params.targetId;
        if (typeof targetId !== "string" || !targetId || targetId.length > 256) throw new Error("浏览器页面标识无效");
        const commands = browserInputCommands(params.events);
        const pending = (browserQueues.get(task) ?? Promise.resolve()).catch(() => {}).then(async () => {
          authorize();
          const listing = await request({ method: "GET", path: "/tabs" });
          if (!Array.isArray(listing.tabs) || !listing.tabs.some(tab => tab.targetId === targetId)) throw new Error("此页面不属于当前任务，或已经关闭");
          let channel = browserChannels.get(targetId);
          if (!channel || channel.closed) {
            const status = await request({ method: "GET", path: "/" });
            const base = new URL(String(status.cdpUrl));
            if (base.protocol !== "http:" || !["127.0.0.1", "localhost", "[::1]"].includes(base.hostname) || base.username || base.password) throw new Error("输入仅限当前容器的浏览器");
            const response = await fetch(new URL("/json/list", base), { redirect: "error", signal: AbortSignal.any([client!.connectionSignal!, AbortSignal.timeout(5000)]) });
            if (!response.ok) throw new Error("远端浏览器输入连接失败");
            const targets = await response.json(); authorize();
            if (!Array.isArray(targets)) throw new Error("远端浏览器页面列表无效");
            const target = targets.find(tab => tab.id === targetId);
            if (!target) throw new Error("此浏览器页面已经关闭");
            const endpoint = browserInputEndpoint(base.href, targetId, target);
            if (browserChannels.size >= 8) { const first = browserChannels.keys().next().value!; browserChannels.get(first)?.close(); browserChannels.delete(first); }
            channel = new BrowserInputChannel(endpoint); browserChannels.set(targetId, channel);
          }
          await channel.input(commands, authorize);
        });
        browserQueues.set(task, pending);
        try { await pending; } finally { if (browserQueues.get(task) === pending) browserQueues.delete(task); }
        respond(true, { ok: true });
      } catch (error) { respond(false, undefined, { code: "INVALID_REQUEST", message: error instanceof Error ? error.message : "浏览器输入失败" }); }
    }, { scope: "operator.admin" });
    const inputQueues = new Map<string, Promise<void>>();
    api.registerGatewayMethod("selfme.terminal.input", async ({ params, context, client, respond }) => {
      try {
        const task = taskId(params.task), owner = client?.connId, id = params.sessionId, data = params.data;
        if (!owner || typeof id !== "string" || typeof data !== "string" || Buffer.byteLength(data) > 64 * 1024) throw new Error("终端输入无效");
        const assertCustody = () => {
          if (client?.connectionSignal?.aborted || !context.isTerminalEnabled() || context.terminalSessions?.list().find(row => row.sessionId === id)?.cwd !== join(tasks, task) || !context.terminalSessions.write(owner, id, "")) throw new Error("终端已关闭或不属于此任务与连接");
        };
        if (isTerminalProtocolReply(data)) {
          // DA/theme negotiation belongs to this read-only tmux client, not
          // the task shell. It is allowed during observation, never as input.
          assertCustody();
          if (!context.terminalSessions!.write(owner, id, data)) throw new Error("终端观察连接已关闭");
          respond(true, { ok: true }); return;
        }
        const assertInput = () => {
          if (client?.connectionSignal?.aborted || !controlLease?.ready || controlLease.owner !== owner || controlLease.task !== task) throw new Error("请先停止并接管，再向人工终端输入");
          assertCustody();
        };
        assertInput();
        // Keep the operator PTY itself read-only, including native terminal.input.
        // Authorized input reaches the exact shared shell only through this RPC;
        // native PTY custody and output/resize/close remain in OpenClaw's manager.
        const pending = (inputQueues.get(task) ?? Promise.resolve()).catch(() => {}).then(async () => { assertInput(); await inputTerminal(task, data, assertInput); });
        inputQueues.set(task, pending);
        try { await pending; } finally { if (inputQueues.get(task) === pending) inputQueues.delete(task); }
        respond(true, { ok: true });
      } catch (error) { respond(false, undefined, { code: "INVALID_REQUEST", message: error instanceof Error ? error.message : "终端输入失败" }); }
    }, { scope: "operator.admin" });
    api.registerGatewayMethod("selfme.workspace.prepare", async ({ params, respond }) => {
      try {
        const id = taskId(params.id); const path = join(tasks, id); await mkdir(path, { recursive: true, mode: 0o700 });
        const file = join(path, ".selfme-workspace");
        try { const handle = await open(file, "wx", 0o600); await handle.writeFile(id); await handle.close(); }
        catch (error) { if ((error as NodeJS.ErrnoException).code !== "EEXIST" || (await readFile(file, "utf8")) !== id) throw error; }
        respond(true, { root: await root(id) });
      } catch (error) { respond(false, undefined, { code: "INVALID_REQUEST", message: error instanceof Error ? error.message : "工作区创建失败" }); }
    }, { scope: "operator.write" });
    // Native Gateway authentication and authority guard run before our handler.
    api.registerHttpRoute({ path: "/selfme-lab/files", auth: "gateway", match: "exact", handler: http });
  },
};
