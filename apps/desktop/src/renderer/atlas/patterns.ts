function pattern(
  id: string,
  phase: ExperiencePhase,
  title: string,
  intent: string,
  expected: string,
  checks: string,
  capabilityIds: readonly string[],
  sourceIds: readonly string[],
  surfaces: readonly AtlasSurface[] = ["cross"],
): ExperiencePattern {
  return {
    id,
    phase,
    title,
    intent,
    expected,
    checks: checks.split("|"),
    capabilityIds,
    sourceIds,
    surfaces,
  };
}

