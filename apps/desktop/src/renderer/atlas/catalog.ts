import type {
  AtlasArea,
  AtlasCapability,
  AtlasDomain,
  AtlasFamily,
  AtlasFamilyId,
  AtlasSurface,
} from "./types";

type RawItem = readonly [
  slug: string,
  title: string,
  description: string,
  checks: string,
  surfaces?: readonly AtlasSurface[],
  areas?: readonly AtlasArea[],
];
interface RawDomain {
  id: string;
  familyId: AtlasFamilyId;
  title: string;
  description: string;
  sourceIds: readonly string[];
  surfaces: readonly AtlasSurface[];
  areas: readonly AtlasArea[];
  items: readonly RawItem[];
}

function domain(
  id: string,
  familyId: AtlasFamilyId,
  title: string,
  description: string,
  sourceIds: readonly string[],
  items: readonly RawItem[],
  surfaces: readonly AtlasSurface[] = ["cross"],
  areas: readonly AtlasArea[] = ["cross"],
): RawDomain {
  return {
    id,
    familyId,
    title,
    description,
    sourceIds,
    items,
    surfaces,
    areas,
  };
}

