export const atlasDomains: readonly AtlasDomain[] = rawDomains.map(
  ({ items: _items, ...entry }) => entry,
);
export const atlasCapabilities: readonly AtlasCapability[] = rawDomains.flatMap(
  (entry) =>
    entry.items.map(([slug, title, description, checks, surfaces, areas]) => ({
      id: entry.id + "." + slug,
      domainId: entry.id,
      title,
      description,
      checks: checks.split("|"),
      surfaces: surfaces ?? entry.surfaces,
      areas: areas ?? entry.areas,
    })),
);

export const domainById = new Map(
  atlasDomains.map((entry) => [entry.id, entry]),
);
export const capabilityById = new Map(
  atlasCapabilities.map((entry) => [entry.id, entry]),
);
